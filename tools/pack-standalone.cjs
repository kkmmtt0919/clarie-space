const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
const data=(name,type)=>`data:${type};base64,${fs.readFileSync(path.join(root,'assets',name)).toString('base64')}`;
const images=Object.fromEntries(['cover-about.png','cover-projects.png','cover-world.png','growth-dashboard.png','growth-evidence.png','growth-tasks.png'].map(name=>[name,data(name,'image/png')]));
const embedded={motion:JSON.parse(read('assets/motion.json')),model:fs.readFileSync(path.join(root,'assets','claire-v3.glb')).toString('base64'),images};
images['badge-front.svg']=data('badge-front.svg','image/svg+xml');
images['loading-label.svg']=data('loading-label.svg','image/svg+xml');
images['world-label-paper.svg']=data('world-label-paper.svg','image/svg+xml');
for(const name of ['world-beads.jpg','world-flowers.jpg','world-miniature.jpg','world-letter.jpg']) images[name]=data(name,'image/jpeg');
images['world-cork-board.jpg']=data('world-cork-board.jpg','image/jpeg');
images['world-pushpin.png']=data('world-pushpin.png','image/png');
for(const name of ['sticker-cat.png','sticker-cat-hover.png','sticker-acai.png','paper-crumpled.png','paper-kraft.png']) images[name]=data(name,'image/png');
images['about-title-handwritten.png']=data('about-title-handwritten.png','image/png');
images['paper-backing-landscape.png']=data('paper-backing-landscape.png','image/png');
images['about-floral-border.svg']=data('about-floral-border.svg','image/svg+xml');
embedded.downloads={'番茄专注.exe':data('downloads/番茄专注.exe','application/octet-stream')};
embedded.lanyardModel=fs.readFileSync(path.join(root,'assets','lanyard-card.glb')).toString('base64');
embedded.music=Object.fromEntries(JSON.parse(read('src/music-playlist.json')).map(track=>[track.file,`data:audio/mpeg;base64,${fs.readFileSync(path.join(root,'music',track.file)).toString('base64')}`]));
let html=read('index.html').replace('<link rel="stylesheet" href="./style.css">',()=>`<style>${read('style.css').replace('./assets/world-paper-relief.png',data('world-paper-relief.png','image/png'))}</style>`);
html=html.replace('./assets/about-handwriting.woff2',data('about-handwriting.woff2','font/woff2'));
html=html.replace('./assets/favicon.svg',data('favicon.svg','image/svg+xml')).replace('./assets/hero.jpg',data('hero.jpg','image/jpeg'));
html=html.replace('./assets/loading-label.svg',data('loading-label.svg','image/svg+xml'));
const script=`window.CLAIRE_ASSETS=${JSON.stringify(embedded)};\n${read('app.js')}`.replace(/<\/script/gi,'<\\/script');
html=html.replace('<script src="./app.js" defer></script>',()=>`<script>${script}</script>`);
fs.writeFileSync(path.join(root,'claire.html'),html);
console.log(`Standalone HTML: ${Math.round(Buffer.byteLength(html)/1024)} KB (all assets embedded)`);

